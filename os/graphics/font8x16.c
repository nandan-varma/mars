        case L'S': return GLYPH_S;
        case L'T': return GLYPH_T;
        case L'U': return GLYPH_U;
        case L'V': return GLYPH_V;
        case L'W': return GLYPH_W;
        case L'X': return GLYPH_X;
        case L'Y': return GLYPH_Y;
        case L'Z': return GLYPH_Z;
