const UINT8 *font8x16_get(CHAR16 c) {
    static UINT8 expanded[16];
    const UINT8 *glyph8 = glyph8x8_for(c);

    for (UINTN row = 0; row < 8; ++row) {
        expanded[row * 2] = glyph8[row];
        expanded[row * 2 + 1] = glyph8[row];
    }

    return expanded;
}
